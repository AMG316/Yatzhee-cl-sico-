import random
from collections import Counter
import matplotlib.pyplot as plt

class YahtzeeMonteCarlo:
    def __init__(self):
        self.categories = [
            "Aces", "Twos", "Threes", "Fours", "Fives", "Sixes",
            "Three of a Kind", "Four of a Kind", "Full House",
            "Small Straight", "Large Straight", "Yahtzee", "Chance"
        ]

    def lanzar_dados(self, cantidad):
        return [random.randint(1, 6) for _ in range(cantidad)]

    def evaluar_categoria(self, dados, categoria):
        conteo = Counter(dados)
        if categoria in ["Aces", "Twos", "Threes", "Fours", "Fives", "Sixes"]:
            target = ["Aces", "Twos", "Threes", "Fours", "Fives", "Sixes"].index(categoria) + 1
            return conteo[target] * target
        elif categoria == "Three of a Kind":
            return sum(dados) if any(v >= 3 for v in conteo.values()) else 0
        elif categoria == "Four of a Kind":
            return sum(dados) if any(v >= 4 for v in conteo.values()) else 0
        elif categoria == "Full House":
            counts = list(conteo.values())
            return 25 if (3 in counts and 2 in counts) or 5 in counts else 0
        elif categoria == "Small Straight":
            unique_sets = [{1,2,3,4}, {2,3,4,5}, {3,4,5,6}]
            dados_set = set(dados)
            return 30 if any(s.issubset(dados_set) for s in unique_sets) else 0
        elif categoria == "Large Straight":
            unique_sets = [{1,2,3,4,5}, {2,3,4,5,6}]
            dados_set = set(dados)
            return 40 if any(s.issubset(dados_set) for s in unique_sets) else 0
        elif categoria == "Yahtzee":
            return 50 if any(v == 5 for v in conteo.values()) else 0
        elif categoria == "Chance":
            return sum(dados)
        return 0

    def simular_turno_ia(self):
        dados = self.lanzar_dados(5)
        for _ in range(2):
            conteo = Counter(dados)
            dado_mas_comun, _ = conteo.most_common(1)[0]
            dados_a_conservar = [d for d in dados if d == dado_mas_comun]
            dados_a_relanzar = 5 - len(dados_a_conservar)
            if dados_a_relanzar > 0:
                dados = dados_a_conservar + self.lanzar_dados(dados_a_relanzar)
        return dados

    def simular_partida(self):
        puntuaciones = {"Jugador 1": 0, "Jugador 2": 0}
        tarjetas = {
            "Jugador 1": {cat: None for cat in self.categories},
            "Jugador 2": {cat: None for cat in self.categories}
        }

        for ronda in range(13):
            for jugador in ["Jugador 1", "Jugador 2"]:
                dados_finales = self.simular_turno_ia()
                mejor_puntaje = -1
                mejor_cat = None

                for cat, puntaje_actual in tarjetas[jugador].items():
                    if puntaje_actual is None:
                        pts = self.evaluar_categoria(dados_finales, cat)
                        if pts > mejor_puntaje:
                            mejor_puntaje = pts
                            mejor_cat = cat

                if mejor_cat is None:
                    mejor_cat = next(cat for cat, pts in tarjetas[jugador].items() if pts is None)
                    mejor_puntaje = 0

                tarjetas[jugador][mejor_cat] = mejor_puntaje
                puntuaciones[jugador] += mejor_puntaje

        return puntuaciones

    def ejecutar_montecarlo(self, num_simulaciones=1000):
        victorias_j1, victorias_j2, empates = 0, 0, 0
        scores_j1, scores_j2 = [], []

        for _ in range(num_simulaciones):
            res = self.simular_partida()
            p1, p2 = res["Jugador 1"], res["Jugador 2"]
            scores_j1.append(p1)
            scores_j2.append(p2)

            if p1 > p2:
                victorias_j1 += 1
            elif p2 > p1:
                victorias_j2 += 1
            else:
                empates += 1

        print(f"\n--- RESULTADOS MONTECARLO ({num_simulaciones} PARTIDAS) ---")
        print(f"Probabilidad Victoria J1: {(victorias_j1 / num_simulaciones) * 100:.2f}%")
        print(f"Probabilidad Victoria J2: {(victorias_j2 / num_simulaciones) * 100:.2f}%")
        print(f"Probabilidad Empate:       {(empates / num_simulaciones) * 100:.2f}%")
        print(f"Promedio Puntos J1:        {sum(scores_j1) / num_simulaciones:.2f}")
        print(f"Promedio Puntos J2:        {sum(scores_j2) / num_simulaciones:.2f}\n")

        self.generar_graficos(scores_j1, scores_j2, victorias_j1, victorias_j2, empates, num_simulaciones)

    def generar_graficos(self, scores_j1, scores_j2, v1, v2, emp, n):
        # Gráfico 1: Histograma de puntuaciones
        plt.figure(figsize=(8, 4.5))
        plt.hist(scores_j1, bins=20, alpha=0.6, color='#1f77b4', label='Jugador 1', edgecolor='black')
        plt.hist(scores_j2, bins=20, alpha=0.6, color='#ff7f0e', label='Jugador 2', edgecolor='black')
        plt.axvline(sum(scores_j1)/n, color='blue', linestyle='--', label=f'Promedio J1: {sum(scores_j1)/n:.1f}')
        plt.axvline(sum(scores_j2)/n, color='orange', linestyle='--', label=f'Promedio J2: {sum(scores_j2)/n:.1f}')
        plt.title('Distribución de Puntuaciones (Montecarlo)')
        plt.xlabel('Puntuación Total')
        plt.ylabel('Frecuencia')
        plt.legend()
        plt.grid(True, linestyle='--', alpha=0.5)
        plt.tight_layout()
        plt.savefig('distribucion_puntuaciones_yahtzee.png', dpi=300)
        plt.close()

        # Gráfico 2: Proporción de victorias
        plt.figure(figsize=(6, 4))
        bars = plt.bar(['Victoria J1', 'Victoria J2', 'Empate'], [v1, v2, emp], color=['#2ca02c', '#d62728', '#7f7f7f'], edgecolor='black')
        plt.title('Resultados Globales de la Simulación')
        plt.ylabel('Partidas')
        for bar in bars:
            yval = bar.get_height()
            plt.text(bar.get_x() + bar.get_width()/2.0, yval + 5, f'{yval} ({yval/n*100:.1f}%)', ha='center', va='bottom', fontweight='bold')
        plt.tight_layout()
        plt.savefig('proporcion_victorias_yahtzee.png', dpi=300)
        plt.close()
        print("Gráficas exportadas como 'distribucion_puntuaciones_yahtzee.png' y 'proporcion_victorias_yahtzee.png'\n")

    def jugar_demo_humano(self):
        print("--- MODO JUEGO INTERACTIVO (1 TURNO DEMO) ---")
        dados = self.lanzar_dados(5)
        print(f"Lanzamiento 1: {dados}")
        for l in range(2, 4):
            resp = input("¿Deseas relanzar algunos dados? (s/n): ").strip().lower()
            if resp != 's':
                break
            indices_str = input("Posiciones a conservar separadas por espacio (1-5): ")
            indices = [int(i)-1 for i in indices_str.split() if i.isdigit() and 1 <= int(i) <= 5]
            dados_conservados = [dados[i] for i in indices]
            dados = dados_conservados + self.lanzar_dados(5 - len(dados_conservados))
            print(f"Lanzamiento {l}: {dados}")
        print(f"Resultado final del turno: {dados}\n")

